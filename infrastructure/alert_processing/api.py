"""HTTP API for generating natural-language reports with Ollama."""

from __future__ import annotations

import os
import json
from datetime import datetime
from pathlib import Path
from typing import Annotated, Any

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

from .ollama import generate_report


class ReportRequest(BaseModel):
    """Optional parameters for one report generation request."""

    now: Annotated[str | None, Field(description="UTC ISO-8601 reference time")] = None
    model: Annotated[str | None, Field(min_length=1)] = None


class ReportResponse(BaseModel):
    """Only the natural-language response generated by Ollama."""

    report: str


def _reference_time(value: str | None) -> str | None:
    if value is None:
        return None
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise HTTPException(
            status_code=400,
            detail="now must be a valid ISO-8601 timestamp",
        ) from exc
    if parsed.tzinfo is None:
        raise HTTPException(
            status_code=400,
            detail="now must include a timezone",
        )
    return parsed.isoformat()


def create_app(
    *,
    summaries_dir: str | Path | None = None,
    report_path: str | Path | None = None,
    ollama_url: str | None = None,
    default_model: str | None = None,
    timeout: float | None = None,
) -> FastAPI:
    """Create the report API using environment-backed production defaults."""
    if report_path is None and summaries_dir is not None:
        report_path = Path(summaries_dir).parent / "report.json"
    analytical_report_path = Path(report_path or os.getenv(
        "REPORT_PATH", "/processed/report.json"))
    base_url = ollama_url or os.getenv(
        "OLLAMA_BASE_URL", "http://ollama:11434")
    model = default_model or os.getenv("OLLAMA_MODEL", "gemma3:4b")
    request_timeout = timeout or float(os.getenv("OLLAMA_TIMEOUT", "300"))

    app = FastAPI(title="IoT Natural Report API", version="1.0.0")

    @app.get("/health")
    def health() -> dict[str, str]:
        return {"status": "ok"}

    @app.post("/api/v1/reports", response_model=ReportResponse)
    def generate_natural_report(request: ReportRequest | None = None) -> ReportResponse:
        request = request or ReportRequest()
        try:
            if not analytical_report_path.is_file():
                raise FileNotFoundError(
                    f"Analytical report does not exist: {analytical_report_path}"
                )
            analytical_report = json.loads(
                analytical_report_path.read_text(encoding="utf-8")
            )
            if not isinstance(analytical_report, dict):
                raise ValueError("Analytical report must contain a JSON object")
            natural_report = generate_report(
                analytical_report,
                base_url=base_url,
                model=request.model or model,
                timeout=request_timeout,
                print_stream=False,
            )
        except HTTPException:
            raise
        except (FileNotFoundError, ValueError) as exc:
            raise HTTPException(status_code=404, detail=str(exc)) from exc
        except RuntimeError as exc:
            raise HTTPException(status_code=502, detail=str(exc)) from exc
        return ReportResponse(report=natural_report)

    return app


app = create_app()
