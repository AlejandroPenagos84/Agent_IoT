"""Request and response models exposed by the HTTP API."""

from __future__ import annotations

from typing import Annotated

from pydantic import BaseModel, Field


class ReportRequest(BaseModel):
    """Optional parameters for one report generation request."""

    now: Annotated[str | None, Field(description="UTC ISO-8601 reference time")] = None
    model: Annotated[str | None, Field(min_length=1)] = None
    broker_id: Annotated[str | None, Field(
        min_length=1, description="Limit the report to one of the caller's brokers")] = None


class ReportResponse(BaseModel):
    """Only the natural-language response generated by Ollama."""

    report: str


class BrokerCreate(BaseModel):
    """Register one customer MQTT broker."""

    name: Annotated[str, Field(min_length=1, max_length=128)]
    host: Annotated[str | None, Field(max_length=255)] = None
    port: Annotated[int | None, Field(ge=1, le=65535)] = None


class BrokerResponse(BaseModel):
    id: str
    tenant_id: str
    name: str
    host: str | None
    port: int | None
    created_at: str
    status: Annotated[str, Field(
        description="pending (sin captura), connected u offline")] = 'pending'
    sensor_id: str | None = None
    last_seen: str | None = None


class EnrollmentKeyResponse(BaseModel):
    """Shown once: the key is stored only as a hash."""

    enrollment_key: str
    install_command: str


class BrokerCreatedResponse(BrokerResponse, EnrollmentKeyResponse):
    """New broker plus the key and command to install its capture."""


class SensorEnrollRequest(BaseModel):
    enrollment_key: Annotated[str, Field(min_length=10, max_length=128)]
    name: Annotated[str | None, Field(min_length=1, max_length=128)] = None


class SensorTokenResponse(BaseModel):
    access_token: str
    token_type: str = 'bearer'
    expires_in: int


class SensorEnrollResponse(SensorTokenResponse):
    """Identity and credentials of the capture; ``sensor_secret`` is shown once."""

    tenant_id: str
    broker_id: str
    sensor_id: str
    sensor_secret: str
    agent_endpoint: str
    agent_server_name: str
    agent_ca: str | None
    refresh_interval_seconds: int


class SensorCreate(BaseModel):
    """Register one capture installation for a broker."""

    name: Annotated[str, Field(min_length=1, max_length=128)]


class SensorResponse(BaseModel):
    id: str
    tenant_id: str
    broker_id: str
    name: str
    created_at: str


class AlertIngest(BaseModel):
    """Alert emitted by the IDS agent."""

    alert_id: Annotated[str, Field(min_length=1, max_length=128)]
    ts: float
    kind: Annotated[str, Field(min_length=1, max_length=32)] = 'class'
    label: Annotated[str, Field(min_length=1, max_length=64)]
    client_id: str | None = None
    ip: str | None = None
    topic: str | None = None
    mse: float | None = None
    source: str | None = None
    tenant_id: str | None = None
    broker_id: str | None = None
    sensor_id: str | None = None


class AlertIngestResponse(BaseModel):
    alert_id: str
    stored: bool


class AlertResponse(BaseModel):
    alert_id: str
    tenant_id: str
    broker_id: str | None
    sensor_id: str | None
    ts: float
    kind: str
    label: str
    client_id: str | None
    ip: str | None
    topic: str | None
    mse: float | None
    source: str | None
    created_at: str
